#!/usr/bin/env node
/**
 * Build assets/gh-direct-data-public.js from gh-direct-data.js (prices stripped).
 * Run after editing GH Direct prices/copy.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcPath = path.join(root, 'assets/gh-direct-data.js');
const outPath = path.join(root, 'assets/gh-direct-data-public.js');

const src = fs.readFileSync(srcPath, 'utf8');
const win = {};
const DATA = new Function('window', src + '\n; return window.GH_DIRECT;')(win);
if (!DATA) {
  console.error('GH_DIRECT missing');
  process.exit(1);
}

DATA.services.forEach((s) => {
  s.price = null;
  s.priceTo = null;
  s.priceLabel = 'contact';
});
DATA.packages.forEach((p) => {
  p.price = null;
  if (p.mode === 'builder') return;
  p.priceLabel = 'quote';
});

const out =
  '/**\n' +
  ' * GH Direct — public catalog (no published prices).\n' +
  ' * Auto-generated by scripts/generate-gh-direct-public.mjs — do not edit by hand.\n' +
  ' */\n' +
  'window.GH_DIRECT = ' +
  JSON.stringify(DATA, null, 2) +
  ';\n';

fs.writeFileSync(outPath, out);
console.log('Wrote', path.relative(root, outPath));
